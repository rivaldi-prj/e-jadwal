// Ekstraksi seluruh nama dosen unik berurutan
export const DOSEN_NAMES = DOSEN_DATA.map(d => d.nama);

// Ekstraksi seluruh mata kuliah unik berurutan abjad
export const MATA_KULIAH_LIST = Array.from(
  new Set(DOSEN_DATA.flatMap(d => d.mataKuliah))
).sort((a, b) => a.localeCompare(b, 'id'));

// Helper untuk mendapatkan daftar MK berdasarkan nama dosen
export function getCoursesByDosen(dosenNama) {
  if (!dosenNama) return MATA_KULIAH_LIST;
  const match = DOSEN_DATA.find(d => d.nama.toLowerCase() === dosenNama.trim().toLowerCase());
  return match ? match.mataKuliah : MATA_KULIAH_LIST;
}

// Helper untuk mendapatkan daftar Dosen pengampu berdasarkan nama MK
export function getDosenByCourse(courseNama) {
  if (!courseNama || !courseNama.trim()) return [];
  const query = courseNama.trim().toLowerCase();
  const matches = DOSEN_DATA.filter(d =>
    d.mataKuliah.some(mk => mk.trim().toLowerCase() === query)
  );
  return matches.map(d => d.nama);
}
